// Concatenate src/ parts (in manifest order) into dist/KREPLIN.html.
// Virtual manifest entries:
//   "@art"  -> generated JS that sets window.KREPLIN_ART = {name: dataURL} from art/raw/*.png
//              (UI art only: minigame sprites mg-* are left out until the minigames are integrated)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src', 'manifest.json'), 'utf8'));

function artPart() {
  const dir = path.join(root, 'art', 'raw');
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.png') && !f.startsWith('mg-')).sort();
  const map = {};
  let bytes = 0;
  for (const f of files) {
    const buf = fs.readFileSync(path.join(dir, f));
    bytes += buf.length;
    map[f.replace(/\.png$/, '')] = 'data:image/png;base64,' + buf.toString('base64');
  }
  console.log(`  @art: ${files.length} images, ${(bytes / 1024).toFixed(0)} KB raw`);
  return '/* generated by tools/build.js from art/raw (do not edit) */\nwindow.KREPLIN_ART = ' + JSON.stringify(map, null, 0).replace(/","/g, '",\n"') + ';\n';
}

const out = manifest.map(n => n === '@art' ? artPart() : fs.readFileSync(path.join(root, 'src', n), 'utf8')).join('\n');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'KREPLIN.html'), out);
console.log(`built dist/KREPLIN.html (${(out.length / 1e6).toFixed(2)} MB, ${manifest.length} parts)`);
