// Concatenate src/ parts (in manifest order) into dist/KREPLIN.html.
// Virtual manifest entries:
//   "@art"  -> generated JS that sets window.KREPLIN_ART = {name: dataURL} from art/raw/*.png
//              (UI art + minigame sprites mg-*; MGKit.load() maps any '<name>.png' URL onto these data URLs)
//   "@audio" -> generated JS that sets window.KREPLIN_AUDIO = {'<dir>/<name>': dataURL} from audio/<dir>/*.mp3
//              (pre-rendered voice lines: commentary/, voicemail/, broadcast/ — see src/087x-voices.js)
// --skip-missing  build even if a manifest part is missing (warns; for testing while another
//                 branch of work has listed parts it hasn't written yet)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src', 'manifest.json'), 'utf8'));

function artPart() {
  const dir = path.join(root, 'art', 'raw');
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.png')).sort();
  const map = {};
  let bytes = 0;
  for (const f of files) {
    const buf = fs.readFileSync(path.join(dir, f));
    bytes += buf.length;
    map[f.replace(/\.png$/, '')] = 'data:image/png;base64,' + buf.toString('base64');
  }
  console.log(`  @art: ${files.length} images, ${(bytes / 1024).toFixed(0)} KB raw`);
  return '/* generated by tools/build.js from art/raw (do not edit) */\nwindow.KREPLIN_ART = ' + JSON.stringify(map, null, 0).replace(/","/g, '",\n"') + ';\n';
}

function audioPart() {
  const base = path.join(root, 'audio');
  const map = {};
  let bytes = 0, n = 0;
  for (const dir of fs.readdirSync(base).filter(d => d !== 'specs' && fs.statSync(path.join(base, d)).isDirectory()).sort()) {
    for (const f of fs.readdirSync(path.join(base, dir)).filter(f => f.endsWith('.mp3')).sort()) {
      const buf = fs.readFileSync(path.join(base, dir, f));
      bytes += buf.length; n++;
      map[`${dir}/${f.replace(/\.mp3$/, '')}`] = 'data:audio/mpeg;base64,' + buf.toString('base64');
    }
  }
  console.log(`  @audio: ${n} clips, ${(bytes / 1024).toFixed(0)} KB raw`);
  return '/* generated by tools/build.js from audio/ (do not edit) */\nwindow.KREPLIN_AUDIO = ' + JSON.stringify(map, null, 0).replace(/","/g, '",\n"') + ';\n';
}

const skipMissing = process.argv.includes('--skip-missing');
const out = manifest.map(n => {
  if (n === '@art') return artPart();
  if (n === '@audio') return audioPart();
  const f = path.join(root, 'src', n);
  if (skipMissing && !fs.existsSync(f)) { console.warn(`  WARNING: skipping missing part ${n}`); return ''; }
  return fs.readFileSync(f, 'utf8');
}).join('\n');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'KREPLIN.html'), out);
console.log(`built dist/KREPLIN.html (${(out.length / 1e6).toFixed(2)} MB, ${manifest.length} parts)`);
