    function update() {
      if (gameState.gameOver) return;
      
      // Update player movement
      let playerDx = 0;
      let playerDy = 0;
      
      if (gameState.keys['w'] || gameState.keys['arrowup']) playerDy -= 1;
      if (gameState.keys['s'] || gameState.keys['arrowdown']) playerDy += 1;
      if (gameState.keys['a'] || gameState.keys['arrowleft']) playerDx -= 1;
      if (gameState.keys['d'] || gameState.keys['arrowright']) playerDx += 1;
      
      if (playerDx !== 0 || playerDy !== 0) {
        const len = Math.sqrt(playerDx * playerDx + playerDy * playerDy);
        playerDx /= len;
        playerDy /= len;
      }
      
      gameState.player.x += playerDx * gameState.player.speed;
      gameState.player.y += playerDy * gameState.player.speed;
      
      // Keep player in bounds (left side of screen)
      gameState.player.x = Math.max(0, Math.min(canvas.width * 0.4, gameState.player.x));
      gameState.player.y = Math.max(0, Math.min(canvas.height - gameState.player.height, gameState.player.y));
      
      // Update jetpack flames
      gameState.player.jetpackFlame += 0.3;
      gameState.krunchem.jetpackFlame += 0.3;
      
      // Update Krunchem - stationary on right side, can move vertically
      const dx = gameState.krunchem.x - gameState.player.x;
      const dy = gameState.krunchem.y - gameState.player.y;
      const dist = Math.sqrt(dx * dx + dy * dy);
      
      // Krunchem moves vertically to avoid player
      if (dist < 400) {
        // Move away from player vertically
        gameState.krunchem.y += (dy / dist) * gameState.krunchem.speed;
      } else {
        // Random vertical movement
        gameState.krunchem.direction += (Math.random() - 0.5) * 0.1;
        gameState.krunchem.y += Math.sin(gameState.krunchem.direction) * gameState.krunchem.speed;
      }
      
      // Keep Krunchem in vertical bounds and on right side
      gameState.krunchem.y = Math.max(50, Math.min(canvas.height - 50, gameState.krunchem.y));
      gameState.krunchem.x = Math.max(canvas.width * 0.6, Math.min(canvas.width - 100, gameState.krunchem.x));
      
      // Krunchem fires rockets at player
      gameState.krunchem.rocketCooldown--;
      const dxRocket = gameState.player.x - gameState.krunchem.x;
      const dyRocket = gameState.player.y - gameState.krunchem.y;
      const distRocket = Math.sqrt(dxRocket * dxRocket + dyRocket * dyRocket);
      
      if (gameState.krunchem.rocketCooldown <= 0 && distRocket < 800) {
        const rocketAngle = Math.atan2(dyRocket, dxRocket);
        gameState.rockets.push({
          x: gameState.krunchem.x + gameState.krunchem.width / 2 + 70, // Fire from bazooka tip
          y: gameState.krunchem.y + gameState.krunchem.height / 2 - 5,
          vx: Math.cos(rocketAngle) * 9, // Faster rockets
          vy: Math.sin(rocketAngle) * 9,
          width: 40, // Much larger rockets
          height: 80, // Long rockets
          rotation: rocketAngle
        });
        gameState.krunchem.rocketCooldown = 40 + Math.random() * 20; // More frequent
        
        // Play rocket fire sound effect
        playRocketFireSound();
      }
      
      // Update rockets
      for (let i = gameState.rockets.length - 1; i >= 0; i--) {
        const rocket = gameState.rockets[i];
        rocket.x += rocket.vx;
        rocket.y += rocket.vy;
        
        // Check collision with player (larger hitbox for larger rockets)
        const rocketCenterX = rocket.x + rocket.width / 2;
        const rocketCenterY = rocket.y + rocket.height / 2;
        const playerCenterX = gameState.player.x + gameState.player.width / 2;
        const playerCenterY = gameState.player.y + gameState.player.height / 2;
        const collisionDist = Math.sqrt(
          Math.pow(rocketCenterX - playerCenterX, 2) + 
          Math.pow(rocketCenterY - playerCenterY, 2)
        );
        
        if (collisionDist < (rocket.width / 2 + gameState.player.width / 2)) {
          gameState.player.health -= 15; // More damage
          gameState.rockets.splice(i, 1);
          
          // Play rocket hit sound effect
          playRocketHitSound();
          
          // Explosion particles
          for (let j = 0; j < 20; j++) {
            gameState.particles.push({
              x: rocket.x + rocket.width / 2,
              y: rocket.y + rocket.height / 2,
              vx: (Math.random() - 0.5) * 15,
              vy: (Math.random() - 0.5) * 15,
              life: 40,
              color: `hsl(${Math.random() * 60}, 100%, 50%)`
            });
          }
          continue;
        }
        
        // Remove if out of bounds
        if (rocket.x < -100 || 
            rocket.x > canvas.width + 100 || 
            rocket.y < -100 || rocket.y > canvas.height + 100) {
          gameState.rockets.splice(i, 1);
        }
      }
      
      // Update bricks - aimed at Krunchem
      for (let i = gameState.bricks.length - 1; i >= 0; i--) {
        const brick = gameState.bricks[i];
        brick.x += brick.vx;
        brick.y += brick.vy;
        
        // Check collision with rockets (bricks are destroyed on contact)
        let brickDestroyed = false;
        for (let j = gameState.rockets.length - 1; j >= 0; j--) {
          const rocket = gameState.rockets[j];
          const brickCenterX = brick.x + brick.width / 2;
          const brickCenterY = brick.y + brick.height / 2;
          const rocketCenterX = rocket.x + rocket.width / 2;
          const rocketCenterY = rocket.y + rocket.height / 2;
          const collisionDist = Math.sqrt(
            Math.pow(brickCenterX - rocketCenterX, 2) + 
            Math.pow(brickCenterY - rocketCenterY, 2)
          );
          
          if (collisionDist < (brick.width / 2 + rocket.width / 2)) {
            // Brick destroyed by rocket - only remove brick, rocket continues
            gameState.bricks.splice(i, 1);
            brickDestroyed = true;
            
            // Explosion particles from brick destruction
            for (let k = 0; k < 15; k++) {
              gameState.particles.push({
                x: brick.x + brick.width / 2,
                y: brick.y + brick.height / 2,
                vx: (Math.random() - 0.5) * 12,
                vy: (Math.random() - 0.5) * 12,
                life: 30,
                color: '#ff0000' // Red particles for destroyed brick
              });
            }
            break; // Exit rocket loop since brick is destroyed
          }
        }
        
        if (brickDestroyed) {
          continue; // Skip force field check since brick is already destroyed
        }
        
        // Check collision with Krunchem force field
        const brickCenterX = brick.x + brick.width / 2;
        const brickCenterY = brick.y + brick.height / 2;
        const krunchemCenterX = gameState.krunchem.x + gameState.krunchem.width / 2;
        const krunchemCenterY = gameState.krunchem.y + gameState.krunchem.height / 2;
        const dx = brickCenterX - krunchemCenterX;
        const dy = brickCenterY - krunchemCenterY;
        const dist = Math.sqrt(dx * dx + dy * dy);
        
        if (dist < 80) { // Force field radius
          gameState.krunchem.forceField -= 2;
          gameState.bricks.splice(i, 1);
          
          // Play brick hit forcefield sound effect
          playBrickHitForceFieldSound();
          
          // Impact particles
          for (let j = 0; j < 8; j++) {
            gameState.particles.push({
              x: brick.x,
              y: brick.y,
              vx: (Math.random() - 0.5) * 8,
              vy: (Math.random() - 0.5) * 8,
              life: 20,
              color: '#ff0000' // Red particles for red bricks
            });
          }
          continue;
        }
        
        // Remove if out of bounds
        if (brick.x < -100 || 
            brick.x > canvas.width + 100 ||
            brick.y < -100 ||
            brick.y > canvas.height + 100) {
          gameState.bricks.splice(i, 1);
        }
      }
      
      // Update particles
      for (let i = gameState.particles.length - 1; i >= 0; i--) {
        const p = gameState.particles[i];
        p.x += p.vx;
        p.y += p.vy;
        p.vy += 0.2;
        p.life--;
        if (p.life <= 0) {
          gameState.particles.splice(i, 1);
        }
      }
      
      // Spawn beer pints occasionally
      if (Math.random() < 0.005) {
        gameState.beerPints.push({
          x: Math.random() * canvas.width,
          y: -20,
          width: 30,
          height: 40,
          vy: 2 + Math.random() * 2,
          rotation: 0,
          rotationSpeed: 0.1
        });
      }
      
      // Update beer pints
      for (let i = gameState.beerPints.length - 1; i >= 0; i--) {
        const beer = gameState.beerPints[i];
        beer.y += beer.vy;
        beer.rotation += beer.rotationSpeed;
        
        // Check collision with player
        if (beer.x < gameState.player.x + gameState.player.width &&
            beer.x + beer.width > gameState.player.x &&
            beer.y < gameState.player.y + gameState.player.height &&
            beer.y + beer.height > gameState.player.y) {
          gameState.player.health = Math.min(gameState.player.maxHealth, gameState.player.health + 20);
          gameState.beerPints.splice(i, 1);
          continue;
        }
        
        // Remove if out of bounds
        if (beer.y > canvas.height + 50 || beer.x < -100 || beer.x > canvas.width + 100) {
          gameState.beerPints.splice(i, 1);
        }
      }
      
      // Update rain
      for (let drop of gameState.rain) {
        drop.y += drop.speed;
        if (drop.y > canvas.height) {
          drop.y = -20;
          drop.x = Math.random() * canvas.width;
        }
      }
      
      // Check win/lose conditions
      if (gameState.krunchem.forceField <= 0) {
        gameState.gameOver = true;
        gameState.won = true;
        // Stop boss fight music when boss is defeated
        if (gameOverlay._bossFightAudio) {
          gameOverlay._bossFightAudio.pause();
          gameOverlay._bossFightAudio.currentTime = 0;
        }
      }
      
      if (gameState.player.health <= 0) {
        gameState.gameOver = true;
        gameState.won = false;
        // Stop boss fight music when player is defeated
        if (gameOverlay._bossFightAudio) {
          gameOverlay._bossFightAudio.pause();
          gameOverlay._bossFightAudio.currentTime = 0;
        }
      }
      
      // Update UI
      const healthPercent = (gameState.player.health / gameState.player.maxHealth) * 100;
      healthBar.style.width = healthPercent + '%';
      
      const forceFieldPercent = Math.max(0, gameState.krunchem.forceField);
      forceFieldLabel.textContent = `Krunchem Force Field: ${Math.ceil(forceFieldPercent)}%`;
    }
    
